using ODStudio.Model;

namespace ODStudio.Generator;

internal static class OdModuleEmitter
{
    public static string Emit(OdGenerationContext context)
    {
        var writer = new CodeWriter();
        writer.Line("// <auto-generated />");
        writer.Line("#nullable enable");
        writer.Line();
        using (writer.Block($"namespace {context.RootNamespace}"))
        {
            using (writer.Block($"public sealed partial class {context.ModuleTypeName} : global::GMCore.IODModule, global::GMCore.IODNetworkModule, global::GMCore.IODMulticastEventNetworkModule, global::GMCore.IODResourceCatalogNetworkModule, global::GMCore.IODDebugModule"))
            {
                writer.Line($"public global::GMCore.ODModuleName Name => new global::GMCore.ODModuleName {{ Name = {OdGenerationContext.StringLiteral(context.ModuleStableName)} }};");
                writer.Line();
                EmitClassMetas(writer, context);
                writer.Line();
                EmitStructMetas(writer, context);
                writer.Line();
                EmitEventMetas(writer, context);
                writer.Line();
                EmitClassSaveMetas(writer, context);
                writer.Line();
                EmitFieldSaveMetas(writer, context);
                writer.Line();
                EmitNetworkSchema(writer, context);
                writer.Line();
                EmitRpcMetas(writer, context);
                writer.Line();
                EmitMulticastEventMetas(writer, context);
                writer.Line();
                EmitCodecs(writer, context);
                writer.Line();
                EmitRpcCodecs(writer, context);
                writer.Line();
                EmitMulticastEventCodecs(writer, context);
                writer.Line();
                EmitDebugMetadata(writer, context);
            }
        }
        return writer.ToString();
    }

    private static void EmitClassMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODClassMeta> GetAllODClassMetas()"))
        {
            foreach (var definition in context.OwnedDefinitions.OfType<OdClassDefinition>())
            {
                writer.Line("yield return new global::GMCore.ODClassMeta");
                writer.Line("{");
                writer.Line("    FromModule = Name,");
                writer.Line($"    Name = {context.FullName(definition)}.ClassName,");
                writer.Line($"    ODType = typeof({context.FullName(definition)}),");
                writer.Line($"    ReplicationMode = global::GMCore.GameplayObjectReplicationMode.{definition.Replication},");
                writer.Line($"    RelevancyMode = global::GMCore.GameplayObjectRelevancyMode.{definition.Relevancy},");
                OdObjectPartitionMode partitionMode = context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep
                    ? OdObjectPartitionMode.Manual
                    : definition.Partition;
                writer.Line($"    PartitionMode = global::GMCore.GameplayObjectPartitionMode.{partitionMode},");
                writer.Line($"    IsEngineManaged = {(context.Project.RootClassId == definition.Id ? "true" : "false")},");
                var directBases = definition.IsClasses.Select(id =>
                    context.Definitions.TryGetValue(id, out var baseDefinition) && baseDefinition is OdClassDefinition
                        ? $"{context.FullName(baseDefinition)}.ClassName"
                        : null).Where(item => item is not null).ToList();
                string baseItems = string.Join(", ", directBases);
                string bases = baseItems.Length > 0
                    ? $"new global::System.Collections.Generic.List<global::GMCore.ODClassName> {{ {baseItems} }}"
                    : "new global::System.Collections.Generic.List<global::GMCore.ODClassName>()";
                writer.Line($"    DirectBaseClasses = {bases},");
                writer.Line("    Fields = new global::System.Collections.Generic.List<global::GMCore.ODFieldMeta>");
                writer.Line("    {");
                foreach (var field in definition.Fields)
                {
                    string fieldRef = $"{context.FullName(definition)}.Fields.{OdGenerationContext.Identifier(field.Name)}";
                    writer.Line("        new global::GMCore.ODFieldMeta");
                    writer.Line("        {");
                    writer.Line($"            FromClass = {context.FullName(definition)}.ClassName,");
                    writer.Line($"            Name = {fieldRef},");
                    if (field.Type.Container != OdContainerKind.Single)
                    {
                        string proxyType = context.FieldTypeName(field, gameplayCollection: true);
                        writer.Line($"            DefaultObject = default({proxyType}),");
                        writer.Line($"            FieldType = typeof({proxyType}),");
                        writer.Line($"            InitialValueFactory = () => {context.CollectionStorageExpression(field)},");
                    }
                    else
                    {
                        writer.Line($"            DefaultObject = {context.DefaultExpression(field)},");
                        writer.Line($"            FieldType = typeof({context.FieldTypeName(field, includeNullable: false)}),");
                    }
                    writer.Line($"            ReplicationMode = global::GMCore.ODFieldReplicationMode.{field.Replication},");
                    writer.Line($"            IsDriven = {(field.Mode == OdFieldMode.Driven ? "true" : "false")},");
                    string drivenBys = FieldReferences(context, context.BaseDrivenByFields(definition, field));
                    string drivingOfs = FieldReferences(context, context.FinalDrivingFields(field));
                    writer.Line($"            DrivenBys = new global::System.Collections.Generic.List<global::GMCore.ODFieldName> {{ {drivenBys} }},");
                    writer.Line($"            DrivingOfs = new global::System.Collections.Generic.List<global::GMCore.ODFieldName> {{ {drivingOfs} }},");
                    writer.Line("        },");
                }
                writer.Line("    },");
                writer.Line("};");
            }
            writer.Line("yield break;");
        }
    }

    private static void EmitStructMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODStructMeta> GetAllODStructMetas()"))
        {
            foreach (var definition in context.OwnedDefinitions
                         .Where(item => item is OdResourceDefinition or OdSwitchStructDefinition ||
                                        item is OdStructDefinition structDefinition && context.ShouldEmitStructMetadata(structDefinition)))
            {
                string baseStruct = "null";
                string baseType = "null";
                if (definition is OdStructDefinition { IsStructOf: { } aliasType })
                {
                    baseType = $"typeof({context.TypeName(aliasType, false)})";
                    if (aliasType.DefinitionId is { } targetId &&
                        context.Definitions.TryGetValue(targetId, out OdDefinition? targetDefinition) &&
                        targetDefinition is OdStructDefinition)
                        baseStruct = $"{context.FullName(targetDefinition)}.StructName";
                }
                writer.Line("yield return new global::GMCore.ODStructMeta");
                writer.Line("{");
                writer.Line("    FromModule = Name,");
                writer.Line($"    Name = {context.FullName(definition)}.StructName,");
                writer.Line($"    ODType = typeof({context.FullName(definition)}),");
                writer.Line($"    BaseStruct = {baseStruct},");
                writer.Line($"    BaseType = {baseType},");
                writer.Line("};");
            }
            writer.Line("yield break;");
        }
    }

    private static void EmitEventMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODEventMeta> GetAllODEventMetas()"))
        {
            foreach (var definition in context.OwnedDefinitions.OfType<OdEventDefinition>())
                writer.Line($"yield return new global::GMCore.ODEventMeta {{ FromModule = Name, Name = {context.FullName(definition)}.EventName, ODType = typeof({context.FullName(definition)}), Multicast = {(definition.Multicast ? "true" : "false")} }};");
            foreach (var definition in context.OwnedDefinitions.OfType<OdInterfaceDefinition>().Where(item => !item.Abstract))
                writer.Line($"yield return new global::GMCore.ODEventMeta {{ FromModule = Name, Name = global::{context.Namespace(definition)}.{OdGenerationContext.Identifier(definition.Name)}Param.EventName, ODType = typeof(global::{context.Namespace(definition)}.{OdGenerationContext.Identifier(definition.Name)}Param) }};");
            writer.Line("yield break;");
        }
    }

    private static void EmitClassSaveMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODClassSaveMeta> GetAllODClassSaveMetas()"))
        {
            foreach (var definition in context.OwnedDefinitions.OfType<OdClassDefinition>())
            {
                string stableName = context.ClassStableName(definition);
                writer.Line($"yield return new global::GMCore.ODClassSaveMeta {{ StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(stableName)}), StableName = {OdGenerationContext.StringLiteral(stableName)}, ClassName = {context.FullName(definition)}.ClassName }};");
            }
            writer.Line("yield break;");
        }
    }

    private static void EmitFieldSaveMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODFieldSaveMeta> GetAllODFieldSaveMetas()"))
        {
            foreach (var owner in context.OwnedDefinitions.OfType<OdClassDefinition>())
                foreach (var field in owner.Fields.Where(item => item.Mode != OdFieldMode.Driven))
                {
                    string suffix = $"{owner.Id:N}_{field.Id:N}";
                    string stableName = context.FieldStableName(owner, field);
                    string deltaMembers = field.Type.Container switch
                    {
                        OdContainerKind.Set => $", DeltaKind = global::GMCore.ODCollectionDeltaKind.Set, DeltaKeyWriter = WriteDeltaKey_{suffix}, DeltaKeyReader = ReadDeltaKey_{suffix}",
                        OdContainerKind.Dictionary => $", DeltaKind = global::GMCore.ODCollectionDeltaKind.Map, DeltaKeyWriter = WriteDeltaKey_{suffix}, DeltaKeyReader = ReadDeltaKey_{suffix}, DeltaValueWriter = WriteDeltaValue_{suffix}, DeltaValueReader = ReadDeltaValue_{suffix}",
                        _ => string.Empty,
                    };
                    writer.Line($"yield return new global::GMCore.ODFieldSaveMeta {{ StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(stableName)}), StableName = {OdGenerationContext.StringLiteral(stableName)}, FieldName = {context.FullName(owner)}.Fields.{OdGenerationContext.Identifier(field.Name)}, Writer = Write_{suffix}, Reader = Read_{suffix}{deltaMembers} }};");
                }
            writer.Line("yield break;");
        }
    }

    private static void EmitNetworkSchema(CodeWriter writer, OdGenerationContext context)
    {
        string signature = BuildNetworkSchemaSignature(context);
        writer.Line($"public ulong NetworkSchemaID => global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(signature)});");
        writer.Line($"public ulong ResourceCatalogID => {ResourceCatalogIdExpression(context)};");
    }

    private static string ResourceCatalogIdExpression(OdGenerationContext context)
    {
        if (context.Options.ResourceCatalogIdExpression is { } configured)
            return configured;

        string signature = OdResourceCatalog.BuildSignature(context.Project);
        return $"global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(signature)})";
    }

    private static void EmitRpcMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODRpcMeta> GetAllODRpcMetas()"))
        {
            foreach (var definition in NetworkInterfaces(context))
            {
                string name = OdGenerationContext.Identifier(definition.Name);
                string suffix = definition.Id.ToString("N");
                string stableName = RpcStableName(context, definition);
                string scope = $"global::{context.Namespace(definition)}";
                writer.Line("yield return new global::GMCore.ODRpcMeta");
                writer.Line("{");
                writer.Line($"    StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(stableName)}),");
                writer.Line($"    StableName = {OdGenerationContext.StringLiteral(stableName)},");
                string rpcMode = context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep
                    ? "Lockstep"
                    : definition.Prediction == OdPredictionMode.None ? "Authority" : "Predictable";
                writer.Line($"    Mode = global::GMCore.GameplayRpcMode.{rpcMode},");
                writer.Line("    InterfaceType = global::GMCore.GameplayInterfaceType.PlayerInput,");
                writer.Line($"    ParamType = typeof({scope}.{name}Param),");
                writer.Line($"    ParamWriter = WriteRpcParam_{suffix},");
                writer.Line($"    ParamReader = ReadRpcParam_{suffix},");
                writer.Line("};");
            }
            writer.Line("yield break;");
        }
    }

    private static void EmitMulticastEventMetas(CodeWriter writer, OdGenerationContext context)
    {
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODMulticastEventMeta> GetAllODMulticastEventMetas()"))
        {
            foreach (OdEventDefinition definition in MulticastEvents(context))
            {
                string suffix = definition.Id.ToString("N");
                string stableName = context.EventStableName(definition);
                writer.Line("yield return new global::GMCore.ODMulticastEventMeta");
                writer.Line("{");
                writer.Line($"    StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(stableName)}),");
                writer.Line($"    StableName = {OdGenerationContext.StringLiteral(stableName)},");
                writer.Line($"    EventType = typeof({context.FullName(definition)}),");
                writer.Line($"    Writer = WriteMulticastEvent_{suffix},");
                writer.Line($"    Reader = ReadMulticastEvent_{suffix},");
                writer.Line("};");
            }
            writer.Line("yield break;");
        }
    }

    private static void EmitCodecs(CodeWriter writer, OdGenerationContext context)
    {
        foreach (var owner in context.OwnedDefinitions.OfType<OdClassDefinition>())
            foreach (var field in owner.Fields.Where(item => item.Mode != OdFieldMode.Driven))
            {
                string suffix = $"{owner.Id:N}_{field.Id:N}";
                string typeName = context.FieldTypeName(field);
                using (writer.Block($"private static void Write_{suffix}(global::GMCore.GameplaySaveWriter writer, object boxedValue)"))
                {
                    writer.Line($"{typeName} value = ({typeName})boxedValue;");
                    var codec = new CodecWriter(writer, context);
                    codec.Write(field, "value");
                }
                using (writer.Block($"private static object Read_{suffix}(global::GMCore.GameplaySaveReader reader)"))
                {
                    var codec = new CodecWriter(writer, context);
                    string value = codec.Read(field);
                    writer.Line($"return {value}!;");
                }
                if (field.Type.Container is OdContainerKind.Set or OdContainerKind.Dictionary)
                {
                    OdTypeReference keyType = field.Type.Container == OdContainerKind.Set
                        ? ElementType(field.Type)
                        : DictionaryKeyType(field.Type);
                    EmitDeltaCodec(writer, context, suffix, "Key", keyType,
                        classNotNull: field.Type.Container == OdContainerKind.Dictionary);
                }
                if (field.Type.Container == OdContainerKind.Dictionary)
                    EmitDeltaCodec(writer, context, suffix, "Value", ElementType(field.Type));
            }
    }

    private static void EmitDeltaCodec(
        CodeWriter writer,
        OdGenerationContext context,
        string suffix,
        string part,
        OdTypeReference type,
        bool classNotNull = false)
    {
        string typeName = context.TypeName(type, includeNullable: !classNotNull);
        using (writer.Block($"private static void WriteDelta{part}_{suffix}(global::GMCore.GameplaySaveWriter writer, object boxedValue)"))
        {
            writer.Line($"{typeName} value = ({typeName})boxedValue;");
            new CodecWriter(writer, context).Write(type, "value", classNotNull);
        }
        using (writer.Block($"private static object ReadDelta{part}_{suffix}(global::GMCore.GameplaySaveReader reader)"))
        {
            string value = new CodecWriter(writer, context).Read(type, classNotNull);
            writer.Line($"return {value}!;");
        }
    }

    private static OdTypeReference ElementType(OdTypeReference type) => new()
    {
        BuiltIn = type.BuiltIn,
        DefinitionId = type.DefinitionId,
        IsResourceClass = type.IsResourceClass,
        Nullable = type.Nullable,
    };

    private static OdTypeReference DictionaryKeyType(OdTypeReference type) => new()
    {
        BuiltIn = type.DictionaryKeyBuiltIn,
        DefinitionId = type.DictionaryKeyDefinitionId,
        IsResourceClass = type.DictionaryKeyIsResourceClass,
    };

    private static void EmitRpcCodecs(CodeWriter writer, OdGenerationContext context)
    {
        foreach (var definition in NetworkInterfaces(context))
        {
            string name = OdGenerationContext.Identifier(definition.Name);
            string suffix = definition.Id.ToString("N");
            string scope = $"global::{context.Namespace(definition)}";
            string paramType = $"{scope}.{name}Param";

            using (writer.Block($"private static void WriteRpcParam_{suffix}(global::GMCore.GameplaySaveWriter writer, object boxedValue)"))
            {
                writer.Line($"{paramType} value = ({paramType})boxedValue;");
                var codec = new CodecWriter(writer, context);
                foreach (var field in context.AllInterfaceInputs(definition))
                    codec.Write(field, $"value.{OdGenerationContext.Identifier(field.Name)}", field.NotNull);
            }
            using (writer.Block($"private static object ReadRpcParam_{suffix}(global::GMCore.GameplaySaveReader reader)"))
            {
                writer.Line($"{paramType} result = default;");
                var codec = new CodecWriter(writer, context);
                foreach (var field in context.AllInterfaceInputs(definition))
                {
                    string value = codec.Read(field, field.NotNull);
                    writer.Line($"result.{OdGenerationContext.Identifier(field.Name)} = {value};");
                }
                writer.Line("return result;");
            }
        }
    }

    private static IEnumerable<OdInterfaceDefinition> NetworkInterfaces(OdGenerationContext context) =>
        context.OwnedDefinitions.OfType<OdInterfaceDefinition>()
            .Where(item => !item.Abstract && item.InterfaceType == OdInterfaceType.PlayerInput)
            .OrderBy(item => item.Id);

    private static IEnumerable<OdEventDefinition> MulticastEvents(OdGenerationContext context) =>
        context.OwnedDefinitions.OfType<OdEventDefinition>()
            .Where(item => item.Multicast)
            .OrderBy(item => item.Id);

    private static void EmitMulticastEventCodecs(CodeWriter writer, OdGenerationContext context)
    {
        foreach (OdEventDefinition definition in MulticastEvents(context))
        {
            string suffix = definition.Id.ToString("N");
            string eventType = context.FullName(definition);
            using (writer.Block($"private static void WriteMulticastEvent_{suffix}(global::GMCore.GameplaySaveWriter writer, object boxedValue)"))
            {
                writer.Line($"{eventType} value = ({eventType})boxedValue;");
                var codec = new CodecWriter(writer, context);
                foreach (OdFieldDefinition field in definition.Fields)
                    codec.Write(field, $"value.{OdGenerationContext.Identifier(field.Name)}", field.NotNull);
            }
            using (writer.Block($"private static object ReadMulticastEvent_{suffix}(global::GMCore.GameplaySaveReader reader)"))
            {
                writer.Line($"{eventType} result = default;");
                var codec = new CodecWriter(writer, context);
                foreach (OdFieldDefinition field in definition.Fields)
                {
                    string value = codec.Read(field, field.NotNull);
                    writer.Line($"result.{OdGenerationContext.Identifier(field.Name)} = {value};");
                }
                writer.Line("return result;");
            }
        }
    }

    private static void EmitDebugMetadata(CodeWriter writer, OdGenerationContext context)
    {
        string signature = BuildDebugSchemaSignature(context);
        writer.Line($"public ulong DebugSchemaID => global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(signature)});");
        writer.Line();
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODDebugClassMeta> GetAllODDebugClassMetas()"))
        {
            foreach (OdClassDefinition definition in context.OwnedDefinitions.OfType<OdClassDefinition>())
            {
                writer.Line("yield return new global::GMCore.ODDebugClassMeta");
                writer.Line("{");
                writer.Line($"    StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(context.ClassStableName(definition))}),");
                writer.Line($"    StableName = {OdGenerationContext.StringLiteral(context.ClassStableName(definition))},");
                writer.Line($"    DisplayName = {OdGenerationContext.StringLiteral(definition.Name)},");
                writer.Line($"    ClassName = {context.FullName(definition)}.ClassName,");
                writer.Line($"    IsEngineManaged = {(context.Project.RootClassId == definition.Id ? "true" : "false")},");
                string assignableClassIDs = string.Join(", ", context.AllAssignableClasses(definition)
                    .Select(item => $"global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(context.ClassStableName(item))})"));
                writer.Line($"    AssignableClassIDs = new global::System.Collections.Generic.List<ulong> {{ {assignableClassIDs} }},");
                writer.Line("    Fields = new global::System.Collections.Generic.List<global::GMCore.ODDebugFieldMeta>");
                writer.Line("    {");
                foreach ((OdClassDefinition owner, OdFieldDefinition field) in context.AllFields(definition))
                {
                    string member = OdGenerationContext.Identifier(field.Name);
                    string valueType = DebugValueTypeName(context, field.Type);
                    string keyType = field.Type.Container == OdContainerKind.Dictionary
                        ? $"typeof({DebugKeyTypeName(context, field.Type)})"
                        : "null";
                    writer.Line("        new global::GMCore.ODDebugFieldMeta");
                    writer.Line("        {");
                    writer.Line($"            StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(context.FieldStableName(owner, field))}),");
                    writer.Line($"            StableName = {OdGenerationContext.StringLiteral(context.FieldStableName(owner, field))},");
                    writer.Line($"            DisplayName = {OdGenerationContext.StringLiteral(field.Name)},");
                    writer.Line($"            FieldName = {context.FullName(owner)}.Fields.{member},");
                    writer.Line($"            ValueType = typeof({valueType}),");
                    writer.Line($"            KeyType = {keyType},");
                    writer.Line($"            Container = global::GMCore.GameplayDebugContainerKind.{DebugContainer(field.Type.Container)},");
                    writer.Line($"            IsGameplayObjectReference = {(context.IsClassReference(field.Type) ? "true" : "false")},");
                    writer.Line($"            GameplayObjectClassID = {DebugClassReferenceID(context, field.Type)},");
                    writer.Line($"            IsResourceReference = {(DebugResourceDefinition(context, field.Type) is not null ? "true" : "false")},");
                    writer.Line($"            IsResourceKeyReference = {(field.Type.Container == OdContainerKind.Dictionary && DebugResourceDefinition(context, DebugKeyType(field.Type)) is not null ? "true" : "false")},");
                    writer.Line($"            ResourceOptions = {DebugResourceOptions(context, field.Type)},");
                    writer.Line($"            ResourceKeyOptions = {(field.Type.Container == OdContainerKind.Dictionary ? DebugResourceOptions(context, DebugKeyType(field.Type)) : "null")},");
                    writer.Line($"            IsDriven = {(field.Mode == OdFieldMode.Driven ? "true" : "false")},");
                    writer.Line($"            ReplicationMode = global::GMCore.ODFieldReplicationMode.{field.Replication},");
                    writer.Line($"            Read = (machine, objectID) => (object)machine.GetGameplayObject<{context.FullName(definition)}>(objectID).{member}!,");
                    if (field.Mode != OdFieldMode.Driven && field.Type.Container == OdContainerKind.Single)
                    {
                        writer.Line("            Write = (machine, objectID, value) =>");
                        writer.Line("            {");
                        writer.Line($"                {context.FullName(definition)} target = machine.GetGameplayObject<{context.FullName(definition)}>(objectID);");
                        writer.Line($"                target.{member} = ({context.FieldTypeName(field)})value!;");
                        writer.Line("            },");
                    }
                    writer.Line("        },");
                }
                writer.Line("    },");
                writer.Line("};");
            }
            writer.Line("yield break;");
        }

        writer.Line();
        using (writer.Block("public global::System.Collections.Generic.IEnumerable<global::GMCore.ODDebugInterfaceMeta> GetAllODDebugInterfaceMetas()"))
        {
            foreach (OdInterfaceDefinition definition in context.OwnedDefinitions.OfType<OdInterfaceDefinition>().Where(item => !item.Abstract).OrderBy(item => item.Id))
            {
                string name = OdGenerationContext.Identifier(definition.Name);
                string scope = $"global::{context.Namespace(definition)}";
                string stableName = $"{context.ModuleStableName}:interface:{definition.Id:N}";
                writer.Line("yield return new global::GMCore.ODDebugInterfaceMeta");
                writer.Line("{");
                writer.Line($"    StableID = global::GMCore.ODSaveHash.Compute({OdGenerationContext.StringLiteral(stableName)}),");
                writer.Line($"    StableName = {OdGenerationContext.StringLiteral(stableName)},");
                writer.Line($"    DisplayName = {OdGenerationContext.StringLiteral(definition.Name)},");
                string debugRpcMode = definition.InterfaceType == OdInterfaceType.PlayerInput
                    ? context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep
                        ? "Lockstep"
                        : definition.Prediction == OdPredictionMode.None ? "Authority" : "Predictable"
                    : "None";
                writer.Line($"    RpcMode = global::GMCore.GameplayRpcMode.{debugRpcMode},");
                writer.Line($"    InterfaceType = global::GMCore.GameplayInterfaceType.{definition.InterfaceType},");
                writer.Line($"    IsRoutine = {(definition.IsRoutine ? "true" : "false")},");
                writer.Line($"    ParamType = typeof({scope}.{name}Param),");
                bool hasResult = !definition.IsRoutine &&
                                 definition.InterfaceType == OdInterfaceType.Gameplay;
                writer.Line($"    ResultType = {(hasResult ? $"typeof({scope}.{name}Result)" : "null")},");
                writer.Line($"    Inputs = {DebugInterfaceFields(context, context.AllInterfaceInputs(definition))},");
                writer.Line($"    Outputs = {DebugInterfaceFields(context, definition.Outputs)},");
                writer.Line($"    Invoke = InvokeDebug_{definition.Id:N},");
                writer.Line("};");
            }
            writer.Line("yield break;");
        }

        foreach (OdInterfaceDefinition definition in context.OwnedDefinitions.OfType<OdInterfaceDefinition>().Where(item => !item.Abstract).OrderBy(item => item.Id))
            EmitDebugInvoker(writer, context, definition);
    }

    private static void EmitDebugInvoker(CodeWriter writer, OdGenerationContext context, OdInterfaceDefinition definition)
    {
        string name = OdGenerationContext.Identifier(definition.Name);
        string scope = $"global::{context.Namespace(definition)}";
        string paramType = $"{scope}.{name}Param";
        writer.Line();
        using (writer.Block($"private static global::GMCore.ODDebugInvocationResult InvokeDebug_{definition.Id:N}(global::GMCore.GameplayMachine machine, global::System.Collections.Generic.IReadOnlyDictionary<string, global::GMCore.GameplayDebugValue> inputs)"))
        {
            writer.Line($"{paramType} param = default;");
            foreach (OdFieldDefinition field in context.AllInterfaceInputs(definition))
            {
                string member = OdGenerationContext.Identifier(field.Name);
                string local = $"input_{field.Id:N}";
                string inputType = context.FieldTypeName(field,
                    includeNullable: !(field.NotNull && context.IsLiveClassReference(field)));
                using (writer.Block($"if (inputs.TryGetValue({OdGenerationContext.StringLiteral(field.Name)}, out global::GMCore.GameplayDebugValue? {local}) && {local} is not null)"))
                    writer.Line($"param.{member} = global::GMCore.GameplayDebugValueConverter.ConvertTo<{inputType}>({local}, machine, {DebugResourceOptions(context, field.Type)}, {(field.Type.Container == OdContainerKind.Dictionary ? DebugResourceOptions(context, DebugKeyType(field.Type)) : "null")});");
            }
            if (definition.IsRoutine)
            {
                writer.Line("global::GMCore.CheckableInterfaceResult execution = machine.Execute((global::GMCore.ICheckableRoutine)param, true);");
                writer.Line("return execution.Sussceeded ? global::GMCore.ODDebugInvocationResult.Success() : global::GMCore.ODDebugInvocationResult.Failure(execution.ErrorMessage.ToString());");
            }
            else if (definition.InterfaceType == OdInterfaceType.PlayerInput)
            {
                writer.Line("global::GMCore.CheckableInterfaceResult execution = machine.Execute((global::GMCore.IReplicatedInterface)param);");
                writer.Line("return execution.Sussceeded ? global::GMCore.ODDebugInvocationResult.Success() : global::GMCore.ODDebugInvocationResult.Failure(execution.ErrorMessage.ToString());");
            }
            else
            {
                writer.Line($"global::GMCore.CheckableInterfaceResult<{scope}.{name}Result> execution = machine.Execute<{scope}.{name}Result>(param);");
                writer.Line("return execution.Sussceeded ? global::GMCore.ODDebugInvocationResult.Success(execution.Result) : global::GMCore.ODDebugInvocationResult.Failure(execution.ErrorMessage.ToString());");
            }
        }
    }

