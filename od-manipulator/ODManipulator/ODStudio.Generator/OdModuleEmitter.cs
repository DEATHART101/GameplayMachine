    private static string BuildNetworkSchemaSignature(OdGenerationContext context)
    {
        var parts = context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep
            ? new List<string> { "od-network:12", context.ModuleStableName, "synchronization:Lockstep" }
            : new List<string> { "od-network:11", context.ModuleStableName };
        foreach (var definition in context.OwnedDefinitions.OrderBy(item => item.Id))
        {
            parts.Add($"definition:{definition.Kind}:{definition.Id:N}");
            switch (definition)
            {
                case OdClassDefinition classDefinition:
                    OdObjectPartitionMode partitionMode = context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep
                        ? OdObjectPartitionMode.Manual
                        : classDefinition.Partition;
                    parts.Add($"class:{classDefinition.Replication}:{classDefinition.Relevancy}:{partitionMode}:{string.Join(",", classDefinition.IsClasses.Select(id => id.ToString("N")))}");
                    AddFields(parts, classDefinition.Fields, includeReplication: true);
                    break;
                case OdStructDefinition structDefinition:
                    if (structDefinition.IsStructOf is not null)
                        parts.Add($"is-struct:{TypeIdentity(structDefinition.IsStructOf)}");
                    AddFields(parts, structDefinition.Fields);
                    break;
                case OdResourceDefinition resourceDefinition:
                    parts.Add("resource");
                    AddFields(parts, resourceDefinition.Fields);
                    break;
                case OdSwitchStructDefinition switchStructDefinition:
                    parts.Add("switch-struct");
                    AddFields(parts, switchStructDefinition.Fields);
                    break;
                case OdEnumDefinition enumDefinition:
                    foreach (var member in enumDefinition.Members.OrderBy(item => item.Id))
                        parts.Add($"enum:{member.Id:N}:{member.Value}");
                    break;
                case OdInterfaceDefinition interfaceDefinition when !interfaceDefinition.Abstract && interfaceDefinition.InterfaceType == OdInterfaceType.PlayerInput:
                    parts.Add($"type:PlayerInput:prediction:{interfaceDefinition.Prediction}:base:{interfaceDefinition.BaseInterfaceId?.ToString("N") ?? "none"}");
                    AddFields(parts, context.AllInterfaceInputs(interfaceDefinition));
                    break;
                case OdInterfaceDefinition interfaceDefinition:
                    parts.Add($"type:{interfaceDefinition.InterfaceType}:routine:{interfaceDefinition.IsRoutine}:abstract:{interfaceDefinition.Abstract}:base:{interfaceDefinition.BaseInterfaceId?.ToString("N") ?? "none"}");
                    AddFields(parts, interfaceDefinition.Inputs);
                    AddFields(parts, interfaceDefinition.Outputs);
                    break;
                case OdEventDefinition eventDefinition:
                    parts.Add($"multicast:{eventDefinition.Multicast}");
                    AddFields(parts, eventDefinition.Fields);
                    break;
            }
        }
        return string.Join("|", parts);
    }

    private static void AddFields(ICollection<string> parts, IEnumerable<OdFieldDefinition> fields, bool includeReplication = false)
    {
        foreach (var field in fields.OrderBy(item => item.Id))
            parts.Add($"field:{field.Id:N}:{TypeIdentity(field.Type)}:not-null:{field.NotNull}:mode:{field.Mode}:driven-by:{string.Join(",", field.DrivenByFields.Order())}{(includeReplication ? $":replication:{field.Replication}" : string.Empty)}");
    }

