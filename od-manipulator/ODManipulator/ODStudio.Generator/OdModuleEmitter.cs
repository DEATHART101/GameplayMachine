        private static OdTypeReference SingleWithoutNullable(OdTypeReference type) => new()
        {
            BuiltIn = type.BuiltIn,
            DefinitionId = type.DefinitionId,
            IsResourceClass = type.IsResourceClass,
            Container = OdContainerKind.Single,
            Nullable = false,
        };
        private bool IsValueLike(OdTypeReference type)
        {
            if (type.DefinitionId is { } id && context.Definitions.TryGetValue(id, out var definition))
                return definition is OdStructDefinition or OdSwitchStructDefinition or OdEnumDefinition;
            return type.BuiltIn != OdBuiltInType.String;
        }
        private bool IsResourceReference(OdTypeReference type) =>
            type.DefinitionId is { } id && context.Definitions.TryGetValue(id, out var definition) &&
            definition is OdResourceDefinition;
        private static string RequireValue(string expression, string typeName) =>
            $"({expression} ?? throw new global::System.IO.InvalidDataException(\"Required resource '{typeName}' cannot be null.\"))";
        private string NewLocal(string prefix) => prefix + _local++;
    }
