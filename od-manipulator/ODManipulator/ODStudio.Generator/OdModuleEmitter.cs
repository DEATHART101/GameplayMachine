    private sealed class CodecWriter(CodeWriter writer, OdGenerationContext context)
    {
        private int _local;

        public void Write(OdFieldDefinition field, string expression, bool classNotNull = false) =>
            Write(field.Type, expression, classNotNull, context.ClassResourceDefinition(field));

        public string Read(OdFieldDefinition field, bool classNotNull = false) =>
            Read(field.Type, classNotNull, context.ClassResourceDefinition(field));

        public void Write(OdTypeReference type, string expression, bool classNotNull = false,
            OdClassDefinition? classResource = null)
        {
            classResource ??= context.ResourceClassDefinition(type);
            if (type.Container != OdContainerKind.Single)
            {
                WriteCollection(type, expression, classResource);
                return;
            }
            if (classResource is not null)
            {
                if (type.Nullable)
                {
                    writer.Line($"writer.WriteBoolean({expression} != null);");
                    using (writer.Block($"if ({expression} != null)"))
                        writer.Line(context.ClassResourceWriteStatement(classResource, expression) ??
                                    $"writer.WriteResourceID(global::{context.RootNamespace}.GeneratedResources.GetId({expression}));");
                }
                else
                {
                    writer.Line(context.ClassResourceWriteStatement(classResource, expression) ??
                                $"writer.WriteResourceID(global::{context.RootNamespace}.GeneratedResources.GetId({expression}));");
                }
                return;
            }
            if (type.DefinitionId is { } customDefinitionId &&
                context.Definitions.TryGetValue(customDefinitionId, out var customDefinition) &&
                context.UsesCustomSerialization(customDefinition))
            {
                writer.Line(context.CustomWriteStatement(customDefinition, expression) ??
                            $"writer.WriteCustom(typeof({context.TypeName(type, false)}), {expression});");
                return;
            }
            if (context.IsClassReference(type))
            {
                if (classNotNull)
                {
                    writer.Line($"if (!{expression}.ObjectID.IsValid) throw new global::System.InvalidOperationException(\"NotNull gameplay object reference cannot be null.\");");
                    writer.Line($"writer.WriteObjectID({expression}.ObjectID);");
                    return;
                }
                writer.Line($"writer.WriteBoolean({expression}.HasValue);");
                using (writer.Block($"if ({expression}.HasValue)"))
                    writer.Line($"writer.WriteObjectID({expression}.Value.ObjectID);");
                return;
            }
            if (type.Nullable && IsResourceReference(type))
            {
                writer.Line($"writer.WriteBoolean({expression} != null);");
                using (writer.Block($"if ({expression} != null)"))
                    Write(SingleWithoutNullable(type), expression);
                return;
            }
            if (type.Nullable && IsValueLike(type))
            {
                writer.Line($"writer.WriteBoolean({expression}.HasValue);");
                using (writer.Block($"if ({expression}.HasValue)"))
                    Write(SingleWithoutNullable(type), expression + ".Value");
                return;
            }
            if (type.DefinitionId is { } definitionId && context.Definitions.TryGetValue(definitionId, out var definition))
            {
                switch (definition)
                {
                    case OdClassDefinition:
                        writer.Line($"writer.WriteObjectID({expression}.ObjectID);");
                        return;
                    case OdEnumDefinition:
                        writer.Line($"writer.WriteVarInt32((int){expression});");
                        return;
                    case OdStructDefinition structDefinition:
                        if (structDefinition.IsStructOf is { } aliasType)
                        {
                            Write(aliasType, $"{expression}.Value");
                            return;
                        }
                        foreach (var field in structDefinition.Fields)
                            Write(field, $"{expression}.{OdGenerationContext.Identifier(field.Name)}");
                        return;
                    case OdResourceDefinition:
                        writer.Line($"writer.WriteResourceID(global::{context.RootNamespace}.GeneratedResources.GetId({expression}));");
                        return;
                    case OdSwitchStructDefinition switchStructDefinition:
                        WriteSwitchStruct(switchStructDefinition, expression);
                        return;
                }
            }
            if (context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep &&
                type.BuiltIn is OdBuiltInType.Single or OdBuiltInType.Double or OdBuiltInType.Decimal)
            {
                writer.Line($"writer.WriteInt64({expression}.RawValue);");
                return;
            }
            switch (type.BuiltIn)
            {
                case OdBuiltInType.Boolean: writer.Line($"writer.WriteBoolean({expression});"); break;
                case OdBuiltInType.Int32: writer.Line($"writer.WriteVarInt32({expression});"); break;
                case OdBuiltInType.Int64: writer.Line($"writer.WriteVarInt64({expression});"); break;
                case OdBuiltInType.Single: writer.Line($"writer.WriteSingle({expression});"); break;
                case OdBuiltInType.Double: writer.Line($"writer.WriteDouble({expression});"); break;
                case OdBuiltInType.Decimal: writer.Line($"writer.WriteDecimal({expression});"); break;
                case OdBuiltInType.String: writer.Line($"writer.WriteString({expression});"); break;
                case OdBuiltInType.DateTime: writer.Line($"writer.WriteInt64({expression}.ToBinary());"); break;
                default: writer.Line($"writer.WriteCustom(typeof({context.TypeName(type, false)}), {expression});"); break;
            }
        }

        public string Read(OdTypeReference type, bool classNotNull = false,
            OdClassDefinition? classResource = null)
        {
            classResource ??= context.ResourceClassDefinition(type);
            if (type.Container != OdContainerKind.Single)
                return ReadCollection(type, classResource);
            if (classResource is not null)
            {
                string expression = context.ClassResourceReadExpression(classResource) ??
                                    $"global::{context.RootNamespace}.GeneratedResources.Resolve<{context.ClassResourceTypeName(classResource)}>(reader.ReadResourceID())";
                if (type.Nullable)
                {
                    string variable = NewLocal("resource");
                    writer.Line($"{context.ClassResourceTypeName(classResource)}? {variable} = null;");
                    using (writer.Block("if (reader.ReadBoolean())"))
                        writer.Line($"{variable} = {expression};");
                    return variable;
                }
                return classNotNull ? RequireValue(expression, context.ClassResourceTypeName(classResource)) : expression;
            }
            if (type.DefinitionId is { } customDefinitionId &&
                context.Definitions.TryGetValue(customDefinitionId, out var customDefinition) &&
                context.UsesCustomSerialization(customDefinition))
            {
                string expression = context.CustomReadExpression(customDefinition) ??
                                    $"reader.ReadCustom<{context.TypeName(type, false)}>()";
                return classNotNull ? RequireValue(expression, context.TypeName(type, false)) : expression;
            }
            if (context.IsClassReference(type))
            {
                if (classNotNull)
                {
                    string required = NewLocal("gameplayObject");
                    string objectId = NewLocal("objectId");
                    writer.Line($"global::GMCore.GObjectID {objectId} = reader.ReadObjectID();");
                    writer.Line($"if (!{objectId}.IsValid) throw new global::System.IO.InvalidDataException(\"NotNull gameplay object reference cannot be null.\");");
                    writer.Line($"{context.TypeName(type, false)} {required} = default;");
                    writer.Line($"{required}.Machine = reader.Machine;");
                    writer.Line($"{required}.ObjectID = {objectId};");
                    return required;
                }
                string variable = NewLocal("gameplayObjectReference");
                writer.Line($"{context.TypeName(type)} {variable} = null;");
                using (writer.Block("if (reader.ReadBoolean())"))
                {
                    string actual = NewLocal("gameplayObject");
                    writer.Line($"{context.TypeName(type, false)} {actual} = default;");
                    writer.Line($"{actual}.Machine = reader.Machine;");
                    writer.Line($"{actual}.ObjectID = reader.ReadObjectID();");
                    writer.Line($"{variable} = {actual};");
                }
                return variable;
            }
            if (type.Nullable && IsResourceReference(type))
            {
                string variable = NewLocal("resource");
                writer.Line($"{context.TypeName(type)} {variable} = null;");
                using (writer.Block("if (reader.ReadBoolean())"))
                    writer.Line($"{variable} = {Read(SingleWithoutNullable(type))};");
                return variable;
            }
            if (type.Nullable && IsValueLike(type))
            {
                string variable = NewLocal("nullable");
                writer.Line($"{context.TypeName(type)} {variable} = null;");
                using (writer.Block("if (reader.ReadBoolean())"))
                {
                    string actual = Read(SingleWithoutNullable(type));
                    writer.Line($"{variable} = {actual};");
                }
                return variable;
            }
            if (type.DefinitionId is { } definitionId && context.Definitions.TryGetValue(definitionId, out var definition))
            {
                switch (definition)
                {
                    case OdClassDefinition:
                        {
                            string variable = NewLocal("gameplayObject");
                            writer.Line($"{context.TypeName(type)} {variable} = default;");
                            writer.Line($"{variable}.Machine = reader.Machine;");
                            writer.Line($"{variable}.ObjectID = reader.ReadObjectID();");
                            return variable;
                        }
                    case OdEnumDefinition:
                        return $"({context.TypeName(type)})reader.ReadVarInt32()";
                    case OdStructDefinition structDefinition:
                        {
                            string variable = NewLocal("structure");
                            string initializer = context.IsReferenceType(structDefinition)
                                ? $"new {context.TypeName(type, false)}()"
                                : "default";
                            writer.Line($"{context.TypeName(type)} {variable} = {initializer};");
                            if (structDefinition.IsStructOf is { } aliasType)
                            {
                                string aliasValue = Read(aliasType);
                                writer.Line($"{variable}.Value = {aliasValue};");
                                return variable;
                            }
                            foreach (var field in structDefinition.Fields)
                            {
                                string child = Read(field);
                                writer.Line($"{variable}.{OdGenerationContext.Identifier(field.Name)} = {child};");
                            }
                            return variable;
                        }
                    case OdResourceDefinition:
                        {
                            string expression = $"global::{context.RootNamespace}.GeneratedResources.Resolve<{context.TypeName(type, false)}>(reader.ReadResourceID())";
                            return classNotNull ? RequireValue(expression, context.TypeName(type, false)) : expression;
                        }
                    case OdSwitchStructDefinition switchStructDefinition:
                        return ReadSwitchStruct(switchStructDefinition, type);
                }
            }
            if (context.Project.Runtime.NetworkMode == OdNetworkMode.Lockstep &&
                type.BuiltIn is OdBuiltInType.Single or OdBuiltInType.Double or OdBuiltInType.Decimal)
                return "global::XLockstep.Fixed64.FromRaw(reader.ReadInt64())";
            return type.BuiltIn switch
            {
                OdBuiltInType.Boolean => "reader.ReadBoolean()",
                OdBuiltInType.Int32 => "reader.ReadVarInt32()",
                OdBuiltInType.Int64 => "reader.ReadVarInt64()",
                OdBuiltInType.Single => "reader.ReadSingle()",
                OdBuiltInType.Double => "reader.ReadDouble()",
                OdBuiltInType.Decimal => "reader.ReadDecimal()",
                OdBuiltInType.String => "reader.ReadString()",
                OdBuiltInType.DateTime => "global::System.DateTime.FromBinary(reader.ReadInt64())",
                _ => $"reader.ReadCustom<{context.TypeName(type, false)}>()",
            };
        }

        private void WriteCollection(OdTypeReference type, string expression, OdClassDefinition? classResource)
        {
            writer.Line($"writer.WriteCount({expression} == null ? -1 : {expression}.Count);");
            using (writer.Block($"if ({expression} != null)"))
            {
                if (type.Container == OdContainerKind.Dictionary)
                {
                    string item = NewLocal("item");
                    using (writer.Block($"foreach (global::System.Collections.Generic.KeyValuePair<{context.DictionaryKeyTypeName(type)}, {ElementTypeName(type, classResource)}> {item} in {expression})"))
                    {
                        Write(DictionaryKeyReference(type), $"{item}.Key", classNotNull: true);
                        Write(ElementReference(type), $"{item}.Value", classResource: classResource);
                    }
                }
                else
                {
                    string item = NewLocal("item");
                    using (writer.Block($"foreach ({ElementTypeName(type, classResource)} {item} in {expression})"))
                        Write(ElementReference(type), item, classResource: classResource);
                }
            }
        }

        private void WriteSwitchStruct(OdSwitchStructDefinition definition, string expression)
        {
            string typeName = context.FullName(definition);
            writer.Line($"writer.WriteVarInt32((int){expression}.SwitchType);");
            using (writer.Block($"switch ({expression}.SwitchType)"))
            {
                foreach (OdFieldDefinition field in definition.Fields)
                {
                    string fieldName = OdGenerationContext.Identifier(field.Name);
                    using (writer.Block($"case {typeName}.SwitchTypes.{fieldName}:"))
                    {
                        Write(field, $"{expression}.{fieldName}");
                        writer.Line("break;");
                    }
                }
                using (writer.Block("default:"))
                    writer.Line("throw new global::System.IO.InvalidDataException(\"Unknown switch struct subtype\");");
            }
        }

        private string ReadSwitchStruct(OdSwitchStructDefinition definition, OdTypeReference type)
        {
            string typeName = context.FullName(definition);
            string variable = NewLocal("switchStruct");
            string discriminator = NewLocal("switchType");
            writer.Line($"{context.TypeName(type)} {variable} = default;");
            writer.Line($"{typeName}.SwitchTypes {discriminator} = ({typeName}.SwitchTypes)reader.ReadVarInt32();");
            using (writer.Block($"switch ({discriminator})"))
            {
                foreach (OdFieldDefinition field in definition.Fields)
                {
                    string fieldName = OdGenerationContext.Identifier(field.Name);
                    using (writer.Block($"case {typeName}.SwitchTypes.{fieldName}:"))
                    {
                        string child = Read(field);
                        writer.Line($"{variable}.{fieldName} = {child};");
                        writer.Line("break;");
                    }
                }
                using (writer.Block("default:"))
                    writer.Line("throw new global::System.IO.InvalidDataException(\"Unknown switch struct subtype\");");
            }
            return variable;
        }

        private string ReadCollection(OdTypeReference type, OdClassDefinition? classResource)
        {
            string count = NewLocal("count");
            string collection = NewLocal("collection");
            writer.Line($"int {count} = reader.ReadCount();");
            string collectionType = context.TypeName(type);
            writer.Line($"{collectionType} {collection} = null!;");
            using (writer.Block($"if ({count} >= 0)"))
            {
                string constructor = $"new {context.CollectionStorageTypeName(type)}()";
                writer.Line($"{collection} = {constructor};");
                string index = NewLocal("i");
                using (writer.Block($"for (int {index} = 0; {index} < {count}; {index}++)"))
                {
                    if (type.Container == OdContainerKind.Dictionary)
                    {
                        OdTypeReference keyType = DictionaryKeyReference(type);
                        string keyExpression = Read(keyType, classNotNull: true);
                        string key = NewLocal("key");
                        writer.Line($"{context.TypeName(keyType, includeNullable: false)} {key} = {keyExpression};");
                        string value = Read(ElementReference(type), classResource: classResource);
                        writer.Line($"{collection}.Add({key}, {value});");
                    }
                    else
                    {
                        string value = Read(ElementReference(type), classResource: classResource);
                        writer.Line($"{collection}.Add({value});");
                    }
                }
            }
            return collection;
        }

