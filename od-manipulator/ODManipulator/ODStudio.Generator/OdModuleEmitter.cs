    private static string BuildDebugSchemaSignature(OdGenerationContext context)
    {
        var parts = new List<string> { "od-debug:5", context.ModuleStableName,
            $"root:{context.Project.RootClassId?.ToString("N") ?? "none"}" };
        foreach (OdDefinition definition in context.OwnedDefinitions.OrderBy(item => item.Id))
        {
            parts.Add($"{definition.Kind}:{definition.Id:N}:{definition.Name}");
            if (definition is OdClassDefinition classDefinition)
                parts.Add($"is-classes:{string.Join(",", classDefinition.IsClasses.Select(id => id.ToString("N")))}");
            if (definition is OdFieldContainerDefinition fieldContainer)
                AddFields(parts, fieldContainer.Fields, includeReplication: definition is OdClassDefinition);
            if (definition is OdInterfaceDefinition interfaceDefinition)
            {
                parts.Add($"type:{interfaceDefinition.InterfaceType}:prediction:{interfaceDefinition.Prediction}:routine:{interfaceDefinition.IsRoutine}:abstract:{interfaceDefinition.Abstract}:base:{interfaceDefinition.BaseInterfaceId?.ToString("N") ?? "none"}");
                AddFields(parts, interfaceDefinition.Inputs);
                AddFields(parts, interfaceDefinition.Outputs);
            }
        }
        return string.Join("|", parts);
    }

